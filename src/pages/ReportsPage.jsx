// ─── Pill helpers ─────────────────────────────────────────────────────────────
const RiskPill = ({ risk }) => {
    const c = RISK_COLORS[risk] || RISK_COLORS.Low;
    return (
        <span style={{ background: c.bg, color: c.color, border: `1px solid ${c.border}`, borderRadius: 4, padding: '2px 9px', fontSize: 11, fontWeight: 700, letterSpacing: '0.03em', display: 'inline-block' }}>
            {risk.toUpperCase()}
        </span>
    );
};

const StatusPill = ({ status }) => {
    const c = STATUS_COLORS[status] || STATUS_COLORS.Generated;
    return (
        <span style={{ display: 'inline-flex', alignItems: 'center', gap: 5, background: c.bg, color: c.color, border: `1px solid ${c.border}`, borderRadius: 4, padding: '2px 9px', fontSize: 11, fontWeight: 700 }}>
            {status === 'Processing' && <Loader size={10} style={{ animation: 'spin 1s linear infinite' }} />}
            {status}
        </span>
    );
};

