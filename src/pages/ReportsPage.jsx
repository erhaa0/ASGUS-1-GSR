// ─── Generate New Report Modal ────────────────────────────────────────────────
const GenerateModal = ({ onClose, onGenerated }) => {
    const [zone, setZone] = useState(ZONES[0]);
    const [reportType, setReportType] = useState('Full Report');
    const [fromDate, setFromDate] = useState('2026-02-21');
    const [toDate, setToDate] = useState('2026-02-28');
    const [includeCharts, setIncludeCharts] = useState(true);
    const [generating, setGenerating] = useState(false);

    const handleGenerate = () => {
        setGenerating(true);
        setTimeout(() => {
            const newId = `RPT-${String(Math.floor(Math.random() * 900) + 100)}`;
            const newReport = {
                id: newId, zone, type: reportType,
                risk: 'Medium', by: 'Ahmed Hassan',
                date: '28 Feb 2026', status: 'Generated',
            };
            const content = `ASGUS-1 GSR SYSTEM REPORT\n======================\nReport ID:   ${newId}\nZone:        ${zone}\nReport Type: ${reportType}\nDate Range:  ${fromDate} to ${toDate}\nGenerated:   ${new Date().toISOString()}\nConfidence:  94%\nRisk Level:  Medium\n\nThis report was generated by the ASGUS-1 GSR Intelligent Terrain Movement Detection System.`;
            const blob = new Blob([content], { type: 'text/plain' });
            const url = URL.createObjectURL(blob);
            const a = document.createElement('a');
            a.href = url;
            a.download = `asgus1-report-${newId}.txt`;
            document.body.appendChild(a); a.click(); document.body.removeChild(a);
            URL.revokeObjectURL(url);

            setGenerating(false);
            onClose();
            onGenerated(newReport, 'Report downloaded successfully');
        }, 2000);
    };

    return (
        <div className="modal-overlay" onClick={onClose}>
            <div className="modal-card" onClick={e => e.stopPropagation()}>
                <div className="modal-header">
                    <h3>Generate New Report</h3>
                    <button className="close-btn" onClick={onClose}><X size={18} /></button>
                </div>
                <div className="topbar-divider" style={{ width: '100%', margin: '16px 0' }}></div>
                <div className="modal-body">
                    <div className="input-group">
                        <label>Zone</label>
                        <select className="modal-input" value={zone} onChange={e => setZone(e.target.value)} style={{ cursor: 'pointer' }}>
                            {ZONES.map(z => <option key={z}>{z}</option>)}
                        </select>
                    </div>
                    <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 16 }}>
                        <div className="input-group"><label>From</label><input type="date" value={fromDate} onChange={e => setFromDate(e.target.value)} className="modal-input" /></div>
                        <div className="input-group"><label>To</label><input type="date" value={toDate} onChange={e => setToDate(e.target.value)} className="modal-input" /></div>
                    </div>
                    <div className="input-group">
                        <label>Report Type</label>
                        <div className="pill-group">
                            {['Risk Analysis', 'Movement Summary', 'Full Report'].map(t => (
                                <button key={t} className={`pill-btn ${reportType === t ? 'active' : ''}`} onClick={() => setReportType(t)}>{t}</button>
                            ))}
                        </div>
                    </div>
                    <div className="toggle-group">
                        <span>Include Charts</span>
                        <label className="switch">
                            <input type="checkbox" checked={includeCharts} onChange={() => setIncludeCharts(!includeCharts)} />
                            <span className="slider round"></span>
                        </label>
                    </div>
                    <button className="generate-btn" disabled={generating} onClick={handleGenerate}>
                        {generating ? <div className="spinner"></div> : 'GENERATE PDF →'}
                    </button>
                </div>
            </div>
        </div>
    );
};

